create or replace TABLE CREDITGUARDIAN_AI.CORE.LOAN_APPLICATIONS (
    APPLICATION_ID VARCHAR(20) NOT NULL,
    CUSTOMER_ID VARCHAR(20) NOT NULL,
    APPLICATION_DATE DATE NOT NULL,
    LOAN_TYPE VARCHAR(50),
    REQUESTED_AMOUNT NUMBER(18,2),
    PROPOSED_TENURE_MONTHS NUMBER(38,0),
    PURPOSE VARCHAR(500),
    COLLATERAL_OFFERED VARCHAR(200),
    COLLATERAL_ESTIMATED_VALUE NUMBER(18,2),
    APPLICANT_RISK_SCORE FLOAT,
    APPLICATION_STATUS VARCHAR(20) DEFAULT 'PENDING',
    ASSIGNED_OFFICER VARCHAR(100),
    AI_RECOMMENDATION VARCHAR(20),
    AI_RECOMMENDATION_REASON VARCHAR(1000),
    AI_CONFIDENCE_SCORE FLOAT,
    OFFICER_DECISION VARCHAR(20),
    OFFICER_REMARKS VARCHAR(500),
    DECISION_DATE DATE,
    CURRENCY VARCHAR(3) DEFAULT 'INR',
    CREATED_AT TIMESTAMP_NTZ(9) DEFAULT CURRENT_TIMESTAMP(),
    UPDATED_AT TIMESTAMP_NTZ(9) DEFAULT CURRENT_TIMESTAMP(),
    constraint CHK_APP_STATUS check (APPLICATION_STATUS IN ('PENDING','UNDER_REVIEW','APPROVED','REJECTED','WITHDRAWN','ESCALATED')),
    constraint CHK_AI_REC check (AI_RECOMMENDATION IN ('APPROVE','REJECT','CONDITIONAL_APPROVE','ESCALATE') OR AI_RECOMMENDATION IS NULL),
    constraint CHK_OFFICER_DEC check (OFFICER_DECISION IN ('APPROVED','REJECTED','DEFERRED') OR OFFICER_DECISION IS NULL),
    constraint PK_LOAN_APPLICATIONS primary key (APPLICATION_ID)
) COMMENT = 'Loan application intake pipeline with AI-assisted decisioning';
