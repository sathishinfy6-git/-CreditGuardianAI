create or replace TABLE CREDITGUARDIAN_AI.CORE.CUSTOMERS (
    CUSTOMER_ID VARCHAR(10) NOT NULL,
    COMPANY_NAME VARCHAR(200) NOT NULL,
    SECTOR VARCHAR(100),
    INDUSTRY VARCHAR(100),
    COUNTRY VARCHAR(50),
    STATE_PROVINCE VARCHAR(100),
    ESTABLISHED_YEAR NUMBER(38,0),
    ANNUAL_REVENUE_USD NUMBER(18,2),
    EMPLOYEE_COUNT NUMBER(38,0),
    IS_BANK_CUSTOMER BOOLEAN DEFAULT TRUE,
    CUSTOMER_SINCE DATE,
    RELATIONSHIP_MANAGER VARCHAR(100),
    COMPANY_TYPE VARCHAR(50),
    STOCK_LISTED BOOLEAN,
    STOCK_EXCHANGE VARCHAR(50),
    WEBSITE VARCHAR(200),
    RISK_TIER VARCHAR(20),
    CREATED_AT TIMESTAMP_NTZ(9) DEFAULT CURRENT_TIMESTAMP(),
    UPDATED_AT TIMESTAMP_NTZ(9) DEFAULT CURRENT_TIMESTAMP(),
    primary key (CUSTOMER_ID)
) COMMENT = 'Master table of borrower/company information';
